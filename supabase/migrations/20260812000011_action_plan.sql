-- 行动确认卡、邀请回应、当天状态
--
-- PRD 把「行动确认卡」称为最重要的中间转化节点：
-- 从一句模糊的「有空一起」，转化为一项明确的共同承诺。
-- 此前整个产品缺这一环 —— 池塘里聊完就直接跳到「办完了」，
-- 中间那个「我们确定要一起做这件事」的时刻没有落点。

-- ============================================================
-- 1. 花苞：计划已确认，等待行动
-- ============================================================
-- 对应 PRD 的植物成长阶段：发芽→长叶→生长→花苞→开花。
-- 缺了花苞，「计划确定」和「事情办完」在数据上是同一件事，
-- 于是提醒该在什么时候发、当天状态该从什么时候开始，都无从判断。
alter type pool_state add value if not exists 'planned' after 'active';
